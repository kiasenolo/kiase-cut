RULES = """<h1>連線規則</h1>
<p>節點之間用連線接起來：從一個節點的<b>輸出</b>拉到另一個節點的<b>輸入</b>。</p>
<h3>基本</h3>
<ul>
<li>一個輸入插槽只接一條線；再拉一條線進去，新的取代舊的。一個輸出可以拉出很多條線。</li>
<li>不能接成圈（節點的結果不能繞回它自己的輸入）。</li>
<li>每個節點圖有一個輸入（片段的畫面）和一個輸出（效果的結果）；「預覽」節點只是讓編輯器的預覽看那個節點，不會被匯出。</li>
<li>要整理線路，用「繞線點」；要寫說明，用「框架／註解」。</li>
</ul>
<h3>什麼接什麼</h3>
<p>所有連線帶的都是一張圖片，所以任何輸出都能接到任何圖片輸入；插槽的類型只決定那張圖被怎麼讀（見「資料類型」）。</p>
<ul>
<li><b>圖片接到數字插槽</b>：數字取圖的明度（透明的地方是 0）。逐像素的插槽（菱形）每個像素各讀自己那一點；單一值的插槽（圓點）只讀圖的中心一點。</li>
<li><b>圖片接到向量插槽</b>：紅、綠、藍當成 X、Y、Z。灰階的圖三個值一樣（浮點轉向量）。</li>
<li><b>數字接到數字參數</b>：用「數值」「整數」「布林」「選單」這些常數節點，或「場景時間」、「數學」的結果。</li>
<li><b>角度</b>：節點上的欄位用「度」，但從別的節點接進來的角度數字當「弧度」（和 Blender 一樣）。</li>
<li><b>字串、字體</b>：只能接到文字節點的「文字」和「字體」插槽，別的地方都接不上。</li>
<li><b>矢量輪廓</b>：形狀、文字、SVG 圖片、矢量節點給出的輪廓，只能接到矢量節點（相加、布林運算、旋轉、移動、縮放）。矢量節點的圖片輸出照常能當圖片用。</li>
</ul>
<h3>參數也能接線</h3>
<p>節點上顏色、數值、開關、整數、選單、向量的欄位都有自己的插槽，把線接進去，欄位就改由那條線決定（欄位本身會被藏起來）。曲線和漸層欄位不能接線。</p>
<p>「參數輸入」節點把<b>效果自己的參數</b>接進圖裡：接上去的欄位會出現在「效果」面板，可以在那裡調整、打關鍵幀。種類要一樣（數值接數值、選單接選項一樣的選單）。</p>
<h3>沒被選到的就不算</h3>
<p>「切換」「索引切換」「選單切換」只運算被選到的那一邊，沒選到的圖整條都不會算，所以拿來做效果的開關不會拖慢速度。</p>"""

